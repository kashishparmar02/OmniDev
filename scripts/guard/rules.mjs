// Pure checks behind the repository guardrails.
//
// The git hooks and the CI job both call these functions through cli.mjs, so a
// rule is written once and enforced in both places. Nothing here touches git
// or the file system; callers pass in the text to check and get back a list of
// human-readable problems. An empty list means the check passed.

const COMMIT_TYPES = [
  "feat",
  "fix",
  "docs",
  "chore",
  "refactor",
  "test",
  "ci",
  "build",
  "perf",
  "revert",
];
const SUBJECT_MAX_LENGTH = 72;
const SUBJECT_PATTERN = new RegExp(`^(${COMMIT_TYPES.join("|")})(\\([a-z0-9-]+\\))?!?: \\S`);

const AI_TOOL_NAMES =
  "claude|anthropic|copilot|cursor|openai|chatgpt|codex|gemini|devin|aider|windsurf";
const AI_ATTRIBUTION_PATTERNS = [
  new RegExp(`^co-authored-by:.*\\b(${AI_TOOL_NAMES})\\b`, "im"),
  new RegExp(`generated (with|by).*\\b(${AI_TOOL_NAMES})\\b`, "i"),
];

// High-confidence credential formats. This is the always-on baseline for the
// local hook; the full scan is gitleaks, which CI runs on every pull request.
const SECRET_PATTERNS = [
  ["Atlassian API token", /ATATT[A-Za-z0-9_\-=]{20,}/],
  ["GitHub token", /\b(gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{30,})/],
  ["AWS access key ID", /\b(AKIA|ASIA)[A-Z0-9]{16}\b/],
  ["Slack token", /\bxox[abprs]-[A-Za-z0-9-]{10,}/],
  ["private key", /-----BEGIN [A-Z ]*PRIVATE KEY-----/],
];

const SECRET_FILE_PATTERNS = [
  /(^|\/)\.env(\.(?!example$)[^/]+)?$/,
  /\.pem$/,
  /(^|\/)id_(rsa|ed25519)$/,
];

/**
 * Turns the private-terms list into regular expressions.
 *
 * The list holds one case-insensitive regular expression per line; blank lines
 * and lines starting with "#" are ignored. It exists so that names which must
 * never appear in this public repository can be blocked without publishing
 * the names themselves, which is why it is read from an untracked file or an
 * environment variable and never committed.
 */
export function parsePrivateTerms(source) {
  return source
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line !== "" && !line.startsWith("#"))
    .map((line) => new RegExp(line, "i"));
}

/**
 * Checks one commit message and returns the problems found.
 *
 * Merge and revert commits generated by git are accepted as they are, because
 * their subjects are not written by hand.
 */
export function checkCommitMessage(message, privateTerms = []) {
  const lines = message.split(/\r?\n/).filter((line) => !line.startsWith("#"));
  const subject = lines.find((line) => line.trim() !== "") ?? "";
  const problems = [];

  if (!/^(Merge|Revert) /.test(subject)) {
    if (!SUBJECT_PATTERN.test(subject)) {
      problems.push(
        `Subject must look like "type(scope): summary" with type one of: ${COMMIT_TYPES.join(", ")}.`,
      );
    }
    if (subject.length > SUBJECT_MAX_LENGTH) {
      problems.push(`Subject is ${subject.length} characters; the limit is ${SUBJECT_MAX_LENGTH}.`);
    }
  }

  const body = lines.join("\n");
  if (AI_ATTRIBUTION_PATTERNS.some((pattern) => pattern.test(body))) {
    problems.push("Remove the AI tool attribution (Co-Authored-By or Generated-with line).");
  }
  if (privateTerms.some((term) => term.test(body))) {
    problems.push("Message contains a term from the private-terms list.");
  }
  return problems;
}

/**
 * Checks a path that is about to be committed.
 *
 * .gitignore already keeps these files out, but `git add -f` bypasses it, so
 * the guard checks again at commit time.
 */
export function checkPath(path, privateTerms = []) {
  const problems = [];
  if (SECRET_FILE_PATTERNS.some((pattern) => pattern.test(path))) {
    problems.push(`${path}: this file type usually holds secrets and must not be committed.`);
  }
  if (privateTerms.some((term) => term.test(path))) {
    problems.push(`${path}: path contains a term from the private-terms list.`);
  }
  return problems;
}

/**
 * Checks the added lines of a unified diff for secrets and private terms.
 *
 * Problems name the file and line but never quote the matched text, because
 * this output is printed in public CI logs.
 */
export function checkDiff(diffText, privateTerms = []) {
  const problems = [];
  let path = "";
  let lineNumber = 0;

  for (const line of diffText.split(/\r?\n/)) {
    if (line.startsWith("+++ ")) {
      path = line.slice(4).replace(/^b\//, "");
      continue;
    }
    const hunk = /^@@ -\d+(?:,\d+)? \+(\d+)/.exec(line);
    if (hunk) {
      lineNumber = Number(hunk[1]);
      continue;
    }
    if (!line.startsWith("+")) {
      // Context lines advance the new-file line number; removed lines do not.
      if (line.startsWith(" ")) lineNumber += 1;
      continue;
    }

    const added = line.slice(1);
    for (const [name, pattern] of SECRET_PATTERNS) {
      if (pattern.test(added)) problems.push(`${path}:${lineNumber}: possible ${name}.`);
    }
    if (privateTerms.some((term) => term.test(added))) {
      problems.push(`${path}:${lineNumber}: contains a term from the private-terms list.`);
    }
    lineNumber += 1;
  }
  return problems;
}
